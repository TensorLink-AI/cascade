"""Cascade-MOE-28M training loop (DEC-CA-0050, P1).

Entered from :meth:`Toto2Trainer.train` when ``[training] base_arch =
"cascade_moe"`` — the same ``--trainer`` spec string drives both
architectures, so no dispatch site (worker, audit re-derivation, miner local
scorer) changes. The toto2 path is untouched.

What differs from the toto2 loop (owner's MoE spec, §3–§6):

* **Batched NorMuon** — every 2-D matrix AND each expert matrix (the stacked
  ``(E, d_in, d_out)`` tensors, one NorMuon matrix per expert, per-neuron
  rows = output units) is orthogonalised in one batched Polar Express call.
  Routers, embeddings, heads and 1-D params ride AdamW without weight decay.
* **µP width correction** on the NorMuon LR: ``× (umup_base_d_model /
  d_model) ** mup_lr_exponent``.
* **Loss** = pinball (Q9) + router auxiliaries (balance + z-loss) + the
  copula energy score, the latter weighted so its gradient at the heads'
  shared input never exceeds ``copula_loss_cap`` × the pinball gradient.
* **Loss-free balancing** — after every optimizer step the routing bias moves
  by ``± u`` against each expert's load (summed over micro-batches); frozen
  for the second half of a fork-anneal, and for a lane-B expert leg.
* **Gradient accumulation** (``micro_batches``) so the spec batch fits 48 GB.
* **Power-function EMAs** (Karras et al. 2024) carried across warm-starts;
  the routing bias in an exported EMA is always the live model's.
* **Lane-B expert legs** — only selected rows get gradients, optimizer state
  and EMA copies (``expert_training.ExpertSlices``).
"""


def refuse_moe_knobs(contract: object) -> None:
    """The toto2 trainer ignores the MoE recipe knobs; an armed one would bump
    ``contract_digest`` while changing no numerics — refuse instead."""
    armed = []
    for k, d in _MOE_KNOBS.items():
        v = getattr(contract, k, d)
        if isinstance(v, list):
            v = tuple(v)
        if v != d:
            armed.append(k)
    if armed:
        raise ValueError(f"[training] {sorted(armed)} are cascade_moe recipe knobs; "
                         f"base_arch is {getattr(contract, 'base_arch', '')!r}")


# ── LR shapes ─────────────────────────────────────────────────────────────────


def anneal_lr(pos: int, total: int, base_lr: float, shape: str = "cosine") -> float:
    """Fork-anneal LR from ``base_lr`` at the fork to 0 at ``total`` tokens."""
    x = min(1.0, max(0.0, pos / max(1, total)))
    if shape == "cosine":
        return base_lr * 0.5 * (1.0 + math.cos(math.pi * x))
    if shape == "linear":
        return base_lr * (1.0 - x)
    if shape == "1-sqrt":
        return base_lr * (1.0 - math.sqrt(x))
    raise ValueError(f"unknown anneal_shape {shape!r}")


def mup_lr_factor(contract: object) -> float:
    exp = float(getattr(contract, "mup_lr_exponent", 0.0) or 0.0)
    if not exp:
        return 1.0
    base = float(getattr(contract, "umup_base_d_model", 0) or 0)
    d = float(getattr(contract, "d_model", 0) or 0)
    if base <= 0 or d <= 0:
        raise ValueError("mup_lr_exponent needs umup_base_d_model and d_model > 0")
    return (base / d) ** exp


# ── power-function EMA (Karras et al. 2024, "Analyzing and Improving the
#    Training Dynamics of Diffusion Models", §3.1 / App. C) ────────────────────


def sigma_rel_of_gamma(gamma: float) -> float:
    return math.sqrt((gamma + 1.0) / ((gamma + 2.0) ** 2 * (gamma + 3.0)))


def gamma_for_sigma_rel(sigma_rel: float) -> float:
    """Invert σ_rel(γ) by bisection (σ_rel is decreasing in γ)."""
    if not 0.0 < sigma_rel < sigma_rel_of_gamma(0.0):
        raise ValueError(f"sigma_rel must be in (0, {sigma_rel_of_gamma(0.0):.4f}); got {sigma_rel}")
    lo, hi = 0.0, 1e6
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if sigma_rel_of_gamma(mid) > sigma_rel:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


class PowerEMA:
    """One power-function EMA over a model's PARAMETERS. ``β_t = (1 − 1/t)^(γ+1)``
    — the averaging window grows with training and stays ``σ_rel`` of the
    steps so far. ``t`` persists across warm-starts so a lineage resumes its
    average exactly. Buffers (the routing bias) are never averaged."""

    def __init__(self, model, sigma_rel: float, *, expert_slices=None):
        import torch

        self.sigma_rel = float(sigma_rel)
        self.gamma = gamma_for_sigma_rel(self.sigma_rel)
        self.t = 0
        self.expert_slices = expert_slices
        source = model if expert_slices is None else expert_slices
        self.shadow = {n: p.detach().clone().float() for n, p in source.named_parameters()}
        self._torch = torch

    def update(self, model) -> None:
        self.t += 1
        beta = (1.0 - 1.0 / self.t) ** (self.gamma + 1.0)
        with self._torch.no_grad():
            source = model if self.expert_slices is None else self.expert_slices
            for n, p in source.named_parameters():
                self.shadow[n].mul_(beta).add_(p.detach().float(), alpha=1.0 - beta)

    def export(self, model) -> dict:
        """Live state dict with every parameter replaced by its average — the
        routing bias (a buffer) stays the live model's (spec §6.5)."""
        out = {k: v.detach().cpu().contiguous() for k, v in model.state_dict().items()}
        for n, v in self.shadow.items():
            avg = v.to(out[n].dtype).cpu().contiguous()
            if self.expert_slices is None:
                out[n] = avg
            else:
                # CPU training can alias state_dict; never overwrite the
                # live endpoint while assembling an averaged checkpoint.
                out[n] = out[n].clone()
                out[n].index_copy_(0, self.expert_slices.rows[n].cpu(), avg)
        return out

    def key(self) -> str:
        return f"ema{self.sigma_rel:g}"

    def state_tensors(self) -> dict:
        import torch

        k = self.key()
        out = {f"{k}.{n}": v.detach().cpu().contiguous() for n, v in self.shadow.items()}
        out[f"{k}.__t__"] = torch.tensor(float(self.t), dtype=torch.float64)
        return out

    def load_state_tensors(self, flat: dict) -> bool:
        k = self.key()
        t = flat.get(f"{k}.__t__")
        if t is None:
            return False
        for n in self.shadow:
            v = flat.get(f"{k}.{n}")
            if v is None or tuple(v.shape) != tuple(self.shadow[n].shape):
                raise ValueError(f"power EMA state mismatch for {k}.{n}")
            self.shadow[n] = v.to(self.shadow[n].device, self.shadow[n].dtype).clone()
        self.t = int(t.item())
        return True


# ── batched NorMuon ───────────────────────────────────────────────────────────


def polar_express_batched(G):
    """:func:`toto2_trainer._polar_express` over a leading batch axis: each
    ``G[i]`` is orthogonalised on its own (per-matrix normalisation). A zero
    matrix stays exactly zero, so frozen experts never move."""
    X = G.float()
    transposed = X.size(-2) > X.size(-1)
    if transposed:
        X = X.mT
    X = X / (X.norm(dim=(-2, -1), keepdim=True) * 1.01 + 1e-7)
    for a, b, c in _POLAR_COEFFS:
        A = X @ X.mT
        B = b * A + c * (A @ A)
        X = a * X + B @ X
    if transposed:
        X = X.mT
    return X.to(G.dtype)


class BatchedNorMuonAdamW(_MuonAdamW):
    """:class:`_MuonAdamW` with 3-D expert tensors stepped as a batch of
    independent NorMuon matrices. A stacked expert weight is laid out
    ``(E, d_in, d_out)`` (``x @ W``); NorMuon's per-neuron rows are the output
    units, so it is stepped through its ``(E, d_out, d_in)`` view. 2-D params
    take exactly the toto2 update."""

    def step(self) -> None:
        lr = self.param_groups[0]["lr"]
        for p in self.muon_params:
            if p.grad is None:
                continue
            batched = p.ndim == 3
            g = p.grad.mT if batched else p.grad
            pv = p.data.mT if batched else p.data
            buf = self._bufs.get(p)
            if buf is None:
                buf = self._torch.zeros_like(g)
                self._bufs[p] = buf
            buf.mul_(self.momentum).add_(g)
            nest = g.add(buf, alpha=self.momentum)
            if batched:
                update = polar_express_batched(nest)
            else:
                from .toto2_trainer import _polar_express

                update = _polar_express(nest)
            v = self._row_v.get(p)
            if v is None:
                v = self._torch.zeros(*update.shape[:-1], 1, device=p.device, dtype=update.dtype)
                self._row_v[p] = v
            v.mul_(self.beta2).add_((update * update).mean(dim=-1, keepdim=True),
                                    alpha=1.0 - self.beta2)
            normed = update / (v.sqrt() + self.eps)
            dims = (-2, -1)
            update = normed * (update.norm(dim=dims, keepdim=True)
                               / normed.norm(dim=dims, keepdim=True).clamp_min(self.eps))
            scale = max(1.0, (update.shape[-2] / update.shape[-1]) ** 0.5)
            if self.weight_decay:
                cautious = ((update * pv) > 0).to(p.dtype)
                pv.mul_(1.0 - lr * self.weight_decay * cautious)
            pv.add_(update, alpha=-lr * scale)
        if self.adamw is not None:
            self.adamw.step()

    def load_state_tensors(self, flat: dict, names: dict) -> int:
        missing = 0
        for p in self.muon_params:
            n = names[id(p)]
            buf = flat.get(f"muon.{n}.momentum")
            v = flat.get(f"muon.{n}.row_v")
            if buf is None and v is None:
                missing += 1
                continue
            gshape = tuple(p.mT.shape) if p.ndim == 3 else tuple(p.shape)
            if buf is not None:
                if tuple(buf.shape) != gshape:
                    raise ValueError(f"optimizer state shape mismatch for {n!r}: momentum "
                                     f"{tuple(buf.shape)} vs {gshape}")
                self._bufs[p] = buf.detach().clone().to(device=p.device, dtype=p.dtype)
            if v is not None:
                want = gshape[:-1] + (1,)
                if tuple(v.shape) != want:
                    raise ValueError(f"optimizer state shape mismatch for {n!r}: row_v "
                                     f"{tuple(v.shape)} vs {want}")
                self._row_v[p] = v.detach().clone().to(device=p.device, dtype=p.dtype)
        if self.adamw is not None:
            from .toto2_trainer import _apply_adamw_state

            missing += _apply_adamw_state(self.adamw, names, flat)
        return missing


def _is_adamw_param(name: str, p) -> bool:
    return (p.ndim < 2 or "embed" in name or "head" in name or "router" in name)


def build_moe_optimizer(model, contract) -> BatchedNorMuonAdamW:
    def _knob(name, dflt):
        v = getattr(contract, name, None)
        return dflt if v is None else float(v)

    momentum = _knob("muon_momentum", 0.95)
    row_beta2 = _knob("muon_row_beta2", 0.95)
    b1, b2 = _knob("adamw_beta1", 0.9), _knob("adamw_beta2", 0.999)
    adamw_lr_scale = _knob("adamw_lr_scale", 1.0)
    if contract.optimizer != "normuon_adamw":
        raise ValueError("cascade_moe requires optimizer = 'normuon_adamw'")
    router_scale = router_lr_scale(contract)
    muon, adamw, router = [], [], []
    for name, p in model.named_parameters():
        if not p.requires_grad:
            continue
        if not _is_adamw_param(name, p):
            muon.append(p)
        elif router_scale != 1.0 and _is_router_param(name):
            router.append(p)
        else:
            adamw.append(p)
    # Slow router (DEC-CA-0050 v2): the router weights get their OWN AdamW
    # group at router_lr_scale × the AdamW LR. Without the flag the groups
    # are exactly the pre-v2 single AdamW group.
    adamw_groups = ([{"params": adamw}, {"params": router}] if router else adamw)
    opt = BatchedNorMuonAdamW(muon, adamw_groups, lr=contract.base_lr,
                              weight_decay=contract.weight_decay,
                              momentum=momentum, beta2=row_beta2)
    opt.param_groups[0]["lr_scale"] = mup_lr_factor(contract)
    if opt.adamw is not None:
        for i, grp in enumerate(opt.adamw.param_groups):
            grp["betas"] = (b1, b2)
            grp["lr_scale"] = adamw_lr_scale * (router_scale if router and i == 1 else 1.0)
    return opt


def _is_router_param(name: str) -> bool:
    """The router's own weights (``….router.weight``) — not the routing bias
    (a buffer) and not anything merely containing "router" elsewhere."""
    return name.endswith("router.weight")


def router_lr_scale(contract) -> float:
    """The router param group's LR multiplier on this leg: ``[training]
    router_lr_scale`` when the leg is flagged ``router_slow``, else 1.0."""
    if not bool(getattr(contract, "router_slow", False)):
        return 1.0
    v = float(getattr(contract, "router_lr_scale", 1.0) or 1.0)
    if not 0.0 < v <= 1.0:
        raise ValueError(f"[training] router_lr_scale must be in (0, 1]; got {v}")
    return v


def route_bias_scale(contract) -> float:
    """The loss-free routing-bias step multiplier on this leg:
    ``[training] route_bias_rate_scale`` when flagged ``router_slow``, else 1.0."""
    if not bool(getattr(contract, "router_slow", False)):
        return 1.0
    v = float(getattr(contract, "route_bias_rate_scale", 1.0) or 1.0)
    if not 0.0 < v <= 1.0:
        raise ValueError(f"[training] route_bias_rate_scale must be in (0, 1]; got {v}")
    return v


def update_route_bias(layer, load, scale: float) -> None:
    """``layer.update_bias(load)`` with its step × ``scale``. ``scale == 1``
    calls the model's own method (bit-identical); otherwise the same rule —
    ``b += rate × scale × sign(mean(load) − load)`` — applied here, so the
    model source (folded into ``base_arch_digest``) is untouched."""
    if scale == 1.0:
        layer.update_bias(load)
        return
    import torch

    load = layer.last_load if load is None else load
    if load is None:
        return
    with torch.no_grad():
        load = load.float()
        layer.route_bias += (layer.cfg.bias_update_rate * scale) * torch.sign(
            load.mean() - load)


# ── copula loss ───────────────────────────────────────────────────────────────


def copula_energy_loss(pred_q, cop, target, *, n_patches: int, n_samples: int,
                       generator, levels):
    """Energy score of joint sample paths over (channel × step) for the last
    ``n_patches`` predicted patches of each group. ``pred_q`` ``(B, C, P, ps,
    nq)``, ``cop`` ``(B, C, P, ps, r+1)``, ``target`` ``(B, C, P, ps)`` — all
    already aligned (position p predicts patch p+1)."""
    from .moe_model import energy_score, sample_copula_paths

    k = max(1, min(int(n_patches), pred_q.shape[2]))
    B = pred_q.shape[0]
    q = pred_q[:, :, -k:].float().reshape(B, -1, pred_q.shape[-1])
    c = cop[:, :, -k:].float().reshape(B, -1, cop.shape[-1])
    y = target[:, :, -k:].float().reshape(B, -1)
    samples = sample_copula_paths(q, c, int(n_samples), generator=generator, levels=levels)
    return energy_score(samples, y)


def _grad_norm(loss, wrt) -> float:
    import torch

    (g,) = torch.autograd.grad(loss, wrt, retain_graph=True, allow_unused=True)
    return 0.0 if g is None else float(g.detach().float().norm())


# ── the loop ──────────────────────────────────────────────────────────────────


def train_moe(trainer, stream: Iterator, contract, *, training_seed: int, token_budget: int,
              out_dir: Path, logger=None, warm_start_dir: Path | None = None,
              expert_selection: dict | None = None, continuation=None) -> TrainResult:
    import torch

    from .moe_model import (
        QUANTILE_LEVELS,
        Z_CLAMP,
        CascadeMoEConfig,
        CascadeMoEModel,
        causal_standardize,
        moe_param_names,
        param_counts,
    )
    from .toto2_model import patch_anchors

    torch.manual_seed(training_seed)
    np.random.seed(training_seed % (2**32 - 1))
    trainer._enable_determinism(torch, training_seed)

    cfg = CascadeMoEConfig.from_contract(contract)
    model = CascadeMoEModel(cfg).to(trainer.device, trainer.dtype)
    expert_base: dict | None = None
    if expert_selection is not None and warm_start_dir is None:
        raise ValueError("a lane-B expert leg trains against the king: warm_start_dir required")
    if warm_start_dir is not None:
        from safetensors.torch import load_file

        if expert_selection is not None:
            # A lane-B leg starts from the king's SCORED weights — the bytes
            # validators merge into (merge_expert_slices byte-checks the leg
            # against them). Under a power-EMA preset the raw lineage file
            # (weights_stable) is a different tensor set entirely.
            weights = Path(warm_start_dir) / "weights.safetensors"
        else:
            weights = Path(warm_start_dir) / STABLE_WEIGHTS_FILE
            if not weights.is_file():
                weights = Path(warm_start_dir) / "weights.safetensors"
        state = load_file(str(weights))
        if expert_selection is not None:
            expert_base = {k: v.detach().clone().cpu() for k, v in state.items()}
        model.load_state_dict({k: v.to(trainer.device) for k, v in state.items()})
        log.info("warm-start: loaded init weights from %s", weights)
    model.train()
    expert_slices = None
    if expert_selection is not None:
        from .expert_training import ExpertSlices

        expert_slices = ExpertSlices(model, expert_selection)
    parameter_source = model if expert_slices is None else expert_slices
    levels = QUANTILE_LEVELS[: cfg.num_quantiles]
    optimizer = build_moe_optimizer(parameter_source, contract)
    # slow router (DEC-CA-0050 v2): an expert leg freezes router + bias anyway
    bias_scale = route_bias_scale(contract) if expert_selection is None else 1.0

    schedule = str(getattr(contract, "lr_schedule", "warmup_cosine") or "warmup_cosine")
    if schedule not in LR_SCHEDULES:
        raise ValueError(f"unknown [training] lr_schedule {schedule!r}")
    warm_started = warm_start_dir is not None
    optim_resumed = False
    # An expert leg NEVER resumes the king's optimizer state: NorMuon / AdamW
    # momentum would keep moving frozen rows under zero gradients.
    if warm_started and expert_selection is None:
        optim_resumed = trainer._load_optimizer_state(Path(warm_start_dir), optimizer, model)

    anneal_frac = float(getattr(contract, "anneal_fraction", 0.0) or 0.0)
    anneal_shape = str(getattr(contract, "anneal_shape", "cosine") or "cosine")
    if anneal_frac and (not 0.0 < anneal_frac < 1.0 or schedule != "wsd"):
        raise ValueError("[training] anneal_fraction must be in (0, 1) with lr_schedule='wsd'")
    anneal_tokens = int(round(token_budget * anneal_frac))
    stable_state: dict | None = None

    if float(getattr(contract, "ema_decay", 0.0) or 0.0):
        raise ValueError("cascade_moe uses power_ema_sigma_rels, not ema_decay")
    sigmas = tuple(float(s) for s in (getattr(contract, "power_ema_sigma_rels", ()) or ()))
    ema_eval = int(getattr(contract, "power_ema_eval", -1))
    if ema_eval >= len(sigmas) or ema_eval < -1:
        raise ValueError(f"power_ema_eval={ema_eval} out of range for {sigmas}")
    if ema_eval >= 0 and anneal_frac:
        raise ValueError("power_ema_eval and anneal_fraction both pick the scored "
                         "artifact — arm exactly one finished-form mechanism")
    # An expert leg scores a power EMA of ITS OWN training too (owner
    # 2026-10-19), never the king's lineage average: it starts fresh at the
    # king's scored weights, and the export puts the king's exact bytes back on
    # every frozen row (x·β + x·(1−β) ≠ x in floating point; the merge
    # byte-checks them). "leg" scope restarts a lane-A leg's EMAs the same way.
    fresh_emas = (expert_selection is not None
                  or str(getattr(contract, "power_ema_scope", "lineage")) == "leg")
    emas = [PowerEMA(model, s, expert_slices=expert_slices) for s in sigmas]
    if warm_started and emas and not fresh_emas:
        f = Path(warm_start_dir) / POWER_EMA_FILE
        if f.is_file():
            from safetensors.torch import load_file

            flat = load_file(str(f))
            for e in emas:
                e.load_state_tensors(flat)

    _wls = getattr(contract, "warm_lr_scale", None)
    warm_lr_scale = 1.0 if _wls is None else float(_wls)
    eff_base_lr = contract.base_lr * (warm_lr_scale if warm_started else 1.0)
    _gc = getattr(contract, "grad_clip", None)
    grad_clip = 1.0 if _gc is None else float(_gc)
    n_micro = max(1, int(getattr(contract, "micro_batches", 1) or 1))
    cop_cap = float(getattr(contract, "copula_loss_cap", 0.0) or 0.0)
    cop_samples = int(getattr(contract, "copula_samples", 8))
    cop_patches = int(getattr(contract, "copula_patches", 2))
    cop_gen = torch.Generator(device=trainer.device)
    cop_gen.manual_seed(training_seed % (2**63))

    max_ctx_patches = max(2, cfg.context_length // cfg.patch_size)
    warmup = int(getattr(contract, "warmup_tokens", int(token_budget * 0.05)))
    tokens = channel_tokens = step = 0
    last_loss = last_cop = float("nan")
    t0 = time.time()
    deadline: float | None = None
    mask_rng = np.random.default_rng(training_seed % (2**63))
    timed_stream = _TimedStream(stream)
    budget_denomination = getattr(contract, "budget_denomination", "points")
    layers = model.moe_layers()
    health: dict = {}
    restored = continuation.store.load() if continuation is not None else None
    replay_steps = int(restored['step']) if restored else 0
    replay_hash = ""
    batch_index = 0
    active_elapsed = 0.0
    if restored:
        from .continuation import assert_training_runtime
        assert_training_runtime(model, restored)
        if replay_steps < 1 or restored['tokens'] < 0 or restored['tokens'] > token_budget + anneal_tokens + contract.batch_size * contract.context_length:
            raise ValueError('invalid continuation budget/cursor')
        model.load_state_dict({k: v.to(trainer.device) for k, v in restored['model'].items()})
        if expert_slices is not None:
            with torch.no_grad():
                for name, leaf in expert_slices.named_parameters():
                    leaf.copy_(restored['leaves'][name].to(leaf))
            expert_slices.sync()
        names = {id(p): n for n, p in parameter_source.named_parameters()}
        optimizer.load_state_tensors(restored['optimizer'], names)
        for ema in emas:
            if not ema.load_state_tensors(restored['emas']):
                raise ValueError('missing continuation EMA state')
        tokens, channel_tokens, step = restored['tokens'], restored['channel_tokens'], replay_steps
        last_loss, last_cop = restored['last_loss'], restored['last_cop']
        stable_state, health = restored['stable_state'], restored['health']
        active_elapsed = restored['elapsed']
        if not math.isfinite(active_elapsed) or active_elapsed < 0:
            raise ValueError('invalid continuation active wall')
        timed_stream.wait_s = restored['data_wait']

    for arr in iter_training_batches(
        batch_source(timed_stream, contract, patch_size=cfg.patch_size,
                     max_ctx_patches=max_ctx_patches, seed=training_seed),
        patch_size=cfg.patch_size, max_ctx_patches=max_ctx_patches,
        batch_size=contract.batch_size,
        batch_denomination=getattr(contract, "batch_denomination", "series"),
    ):
        if continuation is not None:
            import hashlib

            from .continuation import batch_digest, restore_rng, rng_state, training_runtime
            replay_hash = hashlib.sha256((replay_hash + batch_digest(arr)).encode()).hexdigest()
            batch_index += 1
            if batch_index <= replay_steps:
                if batch_index == replay_steps:
                    if replay_hash != restored['input_hash']:
                        raise ValueError('continuation input replay differs from the original job')
                    restore_rng(restored['rng'])
                    mask_rng.bit_generator.state = restored['mask_rng']
                    cop_gen.set_state(restored['cop_rng'])
                    timed_stream.wait_s = restored['data_wait']
                    t0 = time.time() - active_elapsed
                    remaining = contract.max_train_seconds + (anneal_frac * contract.max_train_seconds if stable_state is not None else 0)
                    if tokens >= token_budget + anneal_tokens or active_elapsed >= remaining:
                        deadline = t0 + remaining
                        break
                continue
        if deadline is None:
            t0 = time.time() - active_elapsed
            deadline = t0 + contract.max_train_seconds
            if restored and stable_state is not None:
                deadline += anneal_frac * contract.max_train_seconds
        if restored and (tokens >= token_budget + anneal_tokens or time.time() >= deadline):
            break
        if isinstance(arr, dict):
            vals_all, dmask_all, roles_all = arr["values"], arr["mask"], arr["roles"]
        else:
            vals_all, dmask_all, roles_all = arr, None, None
        in_anneal = bool(anneal_tokens) and tokens >= token_budget
        if in_anneal:
            lr = anneal_lr(tokens - token_budget, anneal_tokens, eff_base_lr, anneal_shape)
        else:
            lr = _lr_at(tokens, token_budget, warmup, eff_base_lr,
                        schedule=schedule, warm_started=warm_started)
        for grp in optimizer.param_groups:
            grp["lr"] = lr * grp.get("lr_scale", 1.0)
        optimizer.zero_grad(set_to_none=True)
        load_sum = [torch.zeros(cfg.num_experts, dtype=torch.long, device=trainer.device)
                    for _ in layers]
        step_loss = step_cop = 0.0
        splits = np.array_split(np.arange(vals_all.shape[0]), min(n_micro, vals_all.shape[0]))
        for idx in splits:
            vals_np = vals_all[idx]
            data_mask_np = None if dmask_all is None else dmask_all[idx]
            roles_np = None if roles_all is None else roles_all[idx]
            n_batch, n_ch, width = vals_np.shape
            rows = n_batch * n_ch
            num_patches = width // cfg.patch_size
            x = torch.as_tensor(vals_np.reshape(rows, width), device=trainer.device,
                                dtype=torch.float64)
            cpm = sample_cpm_masks(rows, num_patches, c_max=cfg.cpm_c_max,
                                   p_max=cfg.cpm_p_max, rng=mask_rng)
            if roles_np is not None and (roles_np == 2).any():
                cpm[roles_np.reshape(rows) == 2] = False
            mask = torch.as_tensor(cpm, device=trainer.device)
            step_mask = mask[:, :, None].expand(-1, -1, cfg.patch_size).reshape(x.shape).to(x.dtype)
            entry_mask = None
            if data_mask_np is not None and data_mask_np.any():
                data_step = torch.as_tensor(data_mask_np.reshape(rows, width),
                                            device=trainer.device).to(x.dtype)
                step_mask = torch.clamp(step_mask + data_step, max=1.0)
                entry_mask = step_mask.view(n_batch, n_ch, num_patches, cfg.patch_size)
            z, loc, scale = causal_standardize(x, mask=step_mask)
            patches = z.to(trainer.dtype).view(n_batch, n_ch, num_patches, cfg.patch_size)
            roles_t = (None if roles_np is None
                       else torch.as_tensor((roles_np != 0).astype(np.int64), device=trainer.device))
            use_cop = cop_cap > 0 and data_mask_np is None
            out = model(patches,
                        mask=(entry_mask.to(trainer.dtype) if entry_mask is not None
                              else mask.view(n_batch, n_ch, num_patches)),
                        roles=roles_t, with_copula=use_cop)
            pred, cop = out if use_cop else (out, None)
            pred_q = pred[:, :, :-1]
            a_loc, a_scale = patch_anchors(loc, scale, cfg.patch_size)
            a_loc = a_loc.view(n_batch, n_ch, num_patches)
            a_scale = a_scale.view(n_batch, n_ch, num_patches)
            raw = x.view(n_batch, n_ch, num_patches, cfg.patch_size)
            target = torch.asinh(
                (raw[:, :, 1:] - a_loc[:, :, :-1, None]) / a_scale[:, :, :-1, None]
            ).clamp_(-Z_CLAMP, Z_CLAMP).to(trainer.dtype)
            weight = None
            if data_mask_np is not None or roles_np is not None:
                w = torch.ones_like(target)
                if data_mask_np is not None:
                    dm = torch.as_tensor(data_mask_np, device=trainer.device).view(
                        n_batch, n_ch, num_patches, cfg.patch_size)
                    w = w * (1.0 - dm[:, :, 1:].to(w.dtype))
                if roles_np is not None:
                    w = w * torch.as_tensor(roles_np == 0, device=trainer.device).to(
                        w.dtype)[:, :, None, None]
                weight = w
            marg = weighted_pinball_loss(pred_q, target, tuple(levels), weight=weight)
            loss = marg
            if use_cop:
                es = copula_energy_loss(pred_q, cop[:, :, :-1], target, n_patches=cop_patches,
                                        n_samples=cop_samples, generator=cop_gen, levels=levels)
                h = model.last_hidden
                gm, ge = _grad_norm(marg, h), _grad_norm(es, h)
                lam = min(1.0, cop_cap * gm / ge) if ge > 0 else 0.0
                loss = loss + lam * es
                step_cop += float(es.detach()) / len(splits)
            if model.aux_loss is not None:
                loss = loss + model.aux_loss
            (loss / len(splits)).backward()
            step_loss += float(marg.detach()) / len(splits)
            for i, layer in enumerate(layers):
                load_sum[i] += layer.last_load
        torch.nn.utils.clip_grad_norm_(
            [p for p in parameter_source.parameters() if p.requires_grad], grad_clip)
        optimizer.step()
        if expert_slices is not None:
            expert_slices.sync()
        # loss-free balancing: frozen in a lane-B leg and for the second half
        # of the cooldown (DeepSeek-V3 / spec §6.7)
        bias_frozen = expert_selection is not None or (
            in_anneal and tokens - token_budget >= anneal_tokens / 2)
        if not bias_frozen:
            for layer, load in zip(layers, load_sum, strict=True):
                update_route_bias(layer, load, bias_scale)
        for e in emas:
            e.update(model)

        last_loss, last_cop = step_loss, step_cop if cop_cap > 0 else float("nan")
        check_loss_finite(last_loss, step=step, tokens=tokens)
        tokens += batch_points(vals_all, budget_denomination)
        channel_tokens += int(np.prod(vals_all.shape))
        step += 1
        if step % LOG_EVERY_STEPS == 0:
            for layer, load in zip(layers, load_sum, strict=True):
                layer.last_load = load
            health = model.routing_health()
            if logger is not None:
                elapsed = max(1e-6, time.time() - t0)
                logger({
                    "event": "step", "step": step, "loss": last_loss, "lr": lr,
                    "copula_es": last_cop, "tokens": tokens,
                    "tokens_frac": tokens / max(1, token_budget),
                    "throughput_tokens_per_s": tokens / elapsed,
                    "data_wait_frac": round(timed_stream.wait_s / elapsed, 3),
                    "routing_max_over_mean": max(
                        (v["max_over_mean"] for v in health.values()), default=0.0),
                    "routing_dead": sum(v["dead"] for v in health.values()),
                })
        if anneal_tokens and stable_state is None and tokens >= token_budget:
            # Expert legs never export lineage state; their optimizer owns
            # compact leaves rather than the model's frozen dense tensors.
            stable_state = (trainer._stable_snapshot(model, optimizer)
                            if expert_slices is None else {})
            if deadline is not None:
                deadline += anneal_frac * contract.max_train_seconds
        if continuation is not None and continuation.due():
            checkpoint_start = time.time()
            flat_emas = {}
            for ema in emas:
                flat_emas.update(ema.state_tensors())
            names = {id(p): n for n, p in parameter_source.named_parameters()}
            continuation.save({'runtime': training_runtime(model), 'step': step, 'tokens': tokens, 'channel_tokens': channel_tokens,
                'model': model.state_dict(), 'leaves': dict(parameter_source.named_parameters())
                    if expert_slices is not None else {},
                'optimizer': optimizer.state_tensors(names), 'emas': flat_emas,
                'stable_state': stable_state, 'health': health, 'last_loss': last_loss,
                'last_cop': last_cop, 'elapsed': time.time() - t0, 'data_wait': timed_stream.wait_s,
                'rng': rng_state(), 'mask_rng': mask_rng.bit_generator.state,
                'cop_rng': cop_gen.get_state(), 'input_hash': replay_hash})
            overhead = time.time() - checkpoint_start
            # Continuation policy measures active training wall. Snapshot I/O
            # and reconstruction are recovery overhead on both uninterrupted
            # and recovered runs; neither adds optimizer/token budget.
            t0 += overhead
            deadline += overhead
        if tokens >= token_budget + anneal_tokens or time.time() > deadline:
            break

    if restored and batch_index < replay_steps:
        raise ValueError('continuation input ended before the saved cursor')
    if restored and deadline is None:
        # A checkpoint at the final batch needs no additional optimizer step.
        from .continuation import restore_rng
        restore_rng(restored['rng'])
        t0 = time.time() - active_elapsed
    train_seconds = time.time() - t0
    deadline_hit = deadline is not None and tokens < token_budget and time.time() > deadline
    counts = param_counts(model)
    gpu_name = (torch.cuda.get_device_name(0)
                if str(trainer.device).startswith("cuda") and torch.cuda.is_available() else "cpu")
    metrics = {
        "final_loss": last_loss, "steps": step, "tokens_seen": tokens,
        "channel_tokens": channel_tokens, "param_count": counts["total"],
        "active_param_count": counts["active"],
        "throughput_tokens_per_s": tokens / max(1e-6, train_seconds),
        "steps_per_s": round(step / max(1e-6, train_seconds), 3),
        "gpu_name": gpu_name, "deterministic": trainer.deterministic,
        "deadline_hit": deadline_hit,
        "data_wait_s": round(timed_stream.wait_s, 1),
        "data_wait_frac": round(timed_stream.wait_s / max(train_seconds, 1e-6), 3),
        "tokens_frac": round(tokens / max(1, token_budget), 3),
        "lr_schedule": schedule, "optim_state_resumed": optim_resumed,
        "base_arch": "cascade_moe", "micro_batches": n_micro,
        "routing_health": health,
    }
    if cop_cap > 0:
        metrics["copula_es"] = last_cop
    if anneal_tokens:
        metrics["anneal_tokens"] = anneal_tokens
        metrics["anneal_tokens_seen"] = max(0, tokens - token_budget)
    if expert_selection is not None:
        metrics["expert_selection"] = {str(k): list(v) for k, v in expert_selection.items()}
        metrics["expert_training_backend"] = "compact_rows"
        metrics["expert_trainable_param_count"] = sum(
            p.numel() for p in expert_slices.parameters())
    if bool(getattr(contract, "router_slow", False)) and expert_selection is None:
        metrics["router_slow"] = {"router_lr_scale": router_lr_scale(contract),
                                  "route_bias_rate_scale": bias_scale}
    if logger is not None:
        logger({"event": "done", **metrics})

    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    from .ckpt_digest import save_tensors_hashed

    live = {k: v.detach().cpu().contiguous() for k, v in model.state_dict().items()}
    if expert_selection is not None:
        # belt and braces: every frozen tensor / unselected expert row is the
        # king's exact bytes, whatever the optimizer or a dtype cast did
        live = restore_frozen(live, expert_base, expert_selection, moe_param_names(model))
    if ema_eval >= 0:
        # the chosen EMA is the scored artifact; the raw endpoint is the lineage
        # (an expert leg is never a lineage: it ships the scored file only)
        if expert_selection is None:
            save_tensors_hashed(live, out / STABLE_WEIGHTS_FILE)
        scored = emas[ema_eval].export(model)
        if expert_selection is not None:
            scored = restore_frozen(scored, expert_base, expert_selection,
                                    moe_param_names(model))
    else:
        scored = live
    _save_moe_checkpoint(out, scored, cfg, levels, contract)
    if emas and expert_selection is None:
        flat: dict = {}
        for e in emas:
            flat.update(e.state_tensors())
        save_tensors_hashed(flat, out / POWER_EMA_FILE)
    if anneal_tokens and expert_selection is None:
        if stable_state is None:
            stable_state = trainer._stable_snapshot(model, optimizer)
        save_tensors_hashed(stable_state["weights"], out / STABLE_WEIGHTS_FILE)
        save_tensors_hashed(stable_state["optim"], out / OPTIM_STATE_FILE)
    elif schedule == "wsd" and expert_selection is None:
        trainer._save_optimizer_state(out, optimizer, model)
    log.info("trained cascade_moe: params=%d active=%d steps=%d tokens=%d loss=%.4f in %.0fs",
             counts["total"], counts["active"], step, tokens, last_loss, train_seconds)
    return TrainResult(local_dir=out, param_count=counts["total"],
                       train_seconds=train_seconds, metrics=metrics)


def restore_frozen(live: dict, base: dict, selection: dict, names: list) -> dict:
    """``live`` with everything a lane-B leg must not change copied back from
    ``base`` (the king's scored weights, in their stored dtype): every
    non-expert tensor and buffer whole, and every UNSELECTED row of each
    expert tensor. Only the selected rows keep the trained values (cast to the
    base dtype), so ``merge_expert_slices(king, leg)`` cannot refuse it."""
    if base is None or live.keys() != base.keys():
        raise ValueError("expert leg: trained state does not match the king's tensors")
    owned = {n: li for li, pair in enumerate(names) for n in pair}
    out = {}
    for k, b in base.items():
        t = b.clone().contiguous()
        if k in owned:
            rows = sorted(int(r) for r in selection.get(owned[k], selection.get(str(owned[k]), [])))
            if rows:
                t[rows] = live[k][rows].to(t.dtype)
        out[k] = t
    return out


def build_random_init(contract, *, training_seed: int, out_dir: Path) -> Path:
    """Write the random-init checkpoint a v2 leg with ``training_seed``
    starts from (DEC-CA-0055: the "init" bench entry of a random-init seed
    epoch): the same RNG seeding and construction as :func:`train_moe`, on
    CPU in fp32 (construction initialises on CPU; training then casts), saved
    in the leg checkpoint layout the bench sweep loads."""
    import torch

    if contract.base_arch == "cascade_pyramid":
        from .pyramid_trainer import build_random_init as build_pyramid_init

        return build_pyramid_init(contract, training_seed=training_seed, out_dir=out_dir)
    from .moe_model import QUANTILE_LEVELS, CascadeMoEConfig, CascadeMoEModel

    torch.manual_seed(training_seed)
    np.random.seed(training_seed % (2**32 - 1))
    cfg = CascadeMoEConfig.from_contract(contract)
    model = CascadeMoEModel(cfg)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    state = {k: v.detach().contiguous().cpu() for k, v in model.state_dict().items()}
    _save_moe_checkpoint(out, state, cfg, QUANTILE_LEVELS[: cfg.num_quantiles], contract)
    return out


def _save_moe_checkpoint(out: Path, state: dict, cfg, levels, contract) -> None:
    from .ckpt_digest import save_tensors_hashed

    save_tensors_hashed(state, out / "weights.safetensors")
    (out / "config.json").write_text(json.dumps({
        "arch": str(getattr(contract, "arch_preset", "cascade-moe-28m")),
        "moe": cfg.to_dict(),
        "quantile_levels": list(levels),
        "input_transform": getattr(contract, "input_transform", "arcsinh_causal"),
    }, indent=2), encoding="utf-8")
    (out / "model.py").write_text(
        Path(__file__).with_name("moe_model.py").read_text(encoding="utf-8"), encoding="utf-8")
    (out / "forecast_wrapper.py").write_text(_MOE_FORECAST_WRAPPER_PY, encoding="utf-8")
